"""## Generate Original Map and Overlay Review Panels for 1 car image example"""

from pathlib import Path
import numpy as np
from PIL import Image
import matplotlib.pyplot as plt

input_path = Path("ForensicsEval/inputs/car.jpg")
output_dir = Path("ForensicsEval/outputs_binary")


map_path = next(output_dir.glob("car.jpg*"))

original = Image.open(input_path).convert("RGB")
score_map = Image.open(map_path).convert("L").resize(original.size)

scores = np.asarray(score_map) / 255.0

# Colouring only higher-scoring areas for visual review.
review_threshold = 0.40
alpha = np.clip((scores - review_threshold) / (1 - review_threshold), 0, 1) * 0.65

heatmap_rgb = (plt.cm.turbo(scores)[..., :3] * 255).astype(np.uint8)
original_array = np.asarray(original)

overlay = (
    original_array * (1 - alpha[..., None])
    + heatmap_rgb * alpha[..., None]
).astype(np.uint8)

fig, axes = plt.subplots(1, 3, figsize=(18, 6))

axes[0].imshow(original)
axes[0].set_title("Original automobile image")

axes[1].imshow(scores, cmap="gray", vmin=0, vmax=1)
axes[1].set_title("SAFIRE suspicion map\nDark = lower; bright = higher")

axes[2].imshow(overlay)
axes[2].set_title(f"Review overlay (scores ≥ {review_threshold:.2f})")

for axis in axes:
    axis.axis("off")

plt.tight_layout()
plt.savefig("safire_review_panel.png", dpi=200, bbox_inches="tight")
plt.show()

