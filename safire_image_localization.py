"""## Generate Original Map and Overlay Review Panels for all Example Images"""

from pathlib import Path
import numpy as np
from PIL import Image
import matplotlib.pyplot as plt

input_dir = Path("ForensicsEval/inputs")
output_dir = Path("ForensicsEval/outputs_binary")
panel_dir = Path("review_panels")
panel_dir.mkdir(exist_ok=True)

for image_path in input_dir.iterdir():
    if image_path.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
        continue

    map_path = output_dir / f"{image_path.name}.png"
    if not map_path.exists():
        print(f"No SAFIRE map found for {image_path.name}")
        continue

    original = Image.open(image_path).convert("RGB")
    score_map = Image.open(map_path).convert("L").resize(original.size)

    scores = np.asarray(score_map) / 255.0
    heatmap = (plt.cm.turbo(scores)[..., :3] * 255).astype(np.uint8)

    # A display setting only—not a claim that every highlighted pixel is forged.
    threshold = 0.40
    alpha = np.clip((scores - threshold) / (1 - threshold), 0, 1) * 0.65
    overlay = (
        np.asarray(original) * (1 - alpha[..., None])
        + heatmap * alpha[..., None]
    ).astype(np.uint8)

    fig, axes = plt.subplots(1, 3, figsize=(18, 6))
    axes[0].imshow(original); axes[0].set_title("Original")
    axes[1].imshow(scores, cmap="gray", vmin=0, vmax=1); axes[1].set_title("SAFIRE suspicion map")
    axes[2].imshow(overlay); axes[2].set_title("Review overlay")

    for axis in axes:
        axis.axis("off")

    plt.tight_layout()
    panel_path = panel_dir / f"{image_path.stem}_review.png"
    plt.savefig(panel_path, dpi=200, bbox_inches="tight")
    # plt.close()

    print(f"Created: {panel_path}")

